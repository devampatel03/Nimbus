"""POST /chat (synchronous single-turn) and WS /chat/ws (streaming Mode A
conversation), both driven by `request.app.state.graph`
(`src.orchestrator.graph.build_graph`, built once in
`src.api.main.create_app`).

Scope note: "streaming" here means the WebSocket connection stays open
and processes one full turn per received message, not per-token
streaming -- `respond`'s response text is template-composed, not
generated by a real model yet (see `src/orchestrator/graph.py`'s module
docstring; T1.5/T4.6 are still outstanding). There is nothing to stream
at the token level until a real generation model is wired in.

Auth: both routes sit behind `src.api.middleware.auth.JWTAuthMiddleware`,
applied ahead of routing -- an unauthenticated WS handshake never reaches
`chat_ws` at all (rejected at the ASGI layer before `websocket.accept`).
"""

import uuid

from fastapi import APIRouter, Request, WebSocket, WebSocketDisconnect
from pydantic import BaseModel

from src.contracts.tool_intent import ToolIntent, ToolResult
from src.orchestrator.state import AgentState, ConversationTurn

router = APIRouter()


class ChatRequest(BaseModel):
    message: str
    session_id: str | None = None


class ChatResponse(BaseModel):
    session_id: str
    response: str
    tool_calls: list[ToolIntent] = []
    tool_results: list[ToolResult] = []


@router.post("", response_model=ChatResponse)
async def chat(payload: ChatRequest, request: Request) -> ChatResponse:
    session_id = payload.session_id or str(uuid.uuid4())
    state = AgentState(message=payload.message)
    result = await request.app.state.graph.ainvoke(
        state, config={"configurable": {"session_id": session_id}}
    )
    return ChatResponse(
        session_id=session_id,
        response=result["response"],
        tool_calls=result["tool_calls"],
        tool_results=result["tool_results"],
    )


@router.websocket("/ws")
async def chat_ws(websocket: WebSocket) -> None:
    await websocket.accept()
    session_id = websocket.query_params.get("session_id") or str(uuid.uuid4())
    history: list[ConversationTurn] = []
    try:
        while True:
            payload = await websocket.receive_json()
            message = payload.get("message", "")
            state = AgentState(message=message, conversation_history=history)
            result = await websocket.app.state.graph.ainvoke(
                state, config={"configurable": {"session_id": session_id}}
            )
            history = result["conversation_history"]
            await websocket.send_json(
                {
                    "type": "response",
                    "session_id": session_id,
                    "response": result["response"],
                    "tool_results": [r.model_dump(mode="json") for r in result["tool_results"]],
                }
            )
    except WebSocketDisconnect:
        pass
